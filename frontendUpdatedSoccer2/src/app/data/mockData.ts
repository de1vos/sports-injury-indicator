export interface Player {
  id: string;
  firstName: string;
  lastName: string;
  position: string;
  kitNumber: number;
  age: number;
  nationality: string;
  marketValue: string;
  injuryRisk: number;
  gamesPlayed: number;
  minutesPlayed: number;
  injuries: number;
  minutesMissed: number;
  riskTrend: number;
  avgDistance: number;
  sprintsPerMatch: number;
  foulsAgainst: number;
  acuteChronicRatio: number;
  daysSinceLastInjury: number;
  matchDensity: number;
  injuryHistory: InjuryRecord[];
  image?: string;
  height?: string;
  weight?: string;
  dateOfBirth?: string;
  preferredFoot?: string;
  photo?: string;
  riskLevel?: string;
  riskFactors?: string[];
  injuryRiskTrend?: RiskTrendEntry[];
  seasonStats?: SeasonStat[];
  workloadData?: WorkloadData;
  injurySummaryData?: InjurySummaryData;
  nextMatch?: NextMatchData;
}

export interface InjuryRecord {
  diagnosis: string;
  region: string;
  from: string;
  until: string;
  severity?: string;
  daysOut?: number;
}

export interface RiskTrendEntry {
  gw: string;
  season: number;
  risk: number | 'Injured';
}

export interface SeasonStat {
  season: number;
  appearances: number;
  minutes: number;
  rating: number;
  goals: number;
  assists: number;
  tackles: number;
  interceptions: number | null;
  duels_total: number;
  duels_won: number;
  dribbles_attempts: number;
  dribbles_success: number;
  fouls_committed: number;
  fouls_drawn: number | null;
  yellow_cards: number;
  red_cards: number;
}

export interface WorkloadData {
  minutes_last_30d: number;
  matches_last_30d: number;
  acute_chronic_ratio: number;
  match_density_14d: number;
  fouls_against_per_90: number;
  consecutive_90min_starts: number;
}

export interface InjurySummaryData {
  career_total_injuries: number;
  injuries_this_season: number;
  days_since_last_injury: number;
  matches_missed_this_season: number;
  minutes_missed_this_season: number;
  matches_missed_career: number;
}

export interface NextMatchData {
  fixture_id: number;
  date: string;
  home_team: string;
  home_logo: string;
  away_team: string;
  away_logo: string;
  venue: string;
  round: string;
}

export interface Team {
  id: string;
  name: string;
  abbreviation: string;
  accentColor: string;
  logo: string;
  squadSize: number;
  avgRisk: number;
  totalInjuries: number;
  totalMinutesLost: number;
  players: Player[];
}

export interface Match {
  id: string;
  homeTeamId: string;
  awayTeamId: string;
  date: string;
  time: string;
  venue: string;
  status: 'completed' | 'upcoming' | 'ongoing';
  score?: {
    home: number;
    away: number;
  };
  kickoffTime?: string; // ISO timestamp for ongoing matches
}

